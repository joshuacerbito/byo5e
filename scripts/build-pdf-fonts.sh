#!/usr/bin/env bash
# Regenerates src/pdf/vfsFonts.js — the base64 font payload pdfmake embeds
# into the exported PDF. Fraunces and Karla ship from Google Fonts as
# variable fonts; pdfkit (pdfmake's engine) can't read a variable axis, so
# each weight is instanced to a static TTF first, then subset to Latin +
# the punctuation the sheet actually uses.
#
# Requires: python3 with fonttools (pip3 install fonttools brotli), curl.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=src/pdf/vfsFonts.js
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

curl -sL -o "$TMP/fraunces.ttf" "https://raw.githubusercontent.com/google/fonts/main/ofl/fraunces/Fraunces%5BSOFT,WONK,opsz,wght%5D.ttf"
curl -sL -o "$TMP/karla.ttf"    "https://raw.githubusercontent.com/google/fonts/main/ofl/karla/Karla%5Bwght%5D.ttf"
curl -sL -o "$TMP/karla-i.ttf"  "https://raw.githubusercontent.com/google/fonts/main/ofl/karla/Karla-Italic%5Bwght%5D.ttf"

# Latin-1 plus general punctuation: the em/en dashes, curly quotes, bullet,
# multiplication sign and middle dot the sheet builds strings out of.
UNI='U+0020-007E,U+00A0-00FF,U+2010-2015,U+2018-201D,U+2020-2022,U+2026,U+2032-2033,U+2039-203A,U+20B1,U+2122,U+2212'

inst () { # src, outname, axes...
  local src=$1 name=$2; shift 2
  python3 -m fontTools.varLib.instancer "$src" "$@" -o "$TMP/$name.raw.ttf" >/dev/null
  python3 -m fontTools.subset "$TMP/$name.raw.ttf" --unicodes="$UNI" \
    --layout-features='kern,liga,ccmp,locl' --no-hinting --desubroutinize \
    --name-IDs='1,2,4,6' --output-file="$TMP/$name.ttf"
}

inst "$TMP/fraunces.ttf" Fraunces-Bold      wght=700 opsz=24 SOFT=0 WONK=0
inst "$TMP/karla.ttf"    Karla-Regular      wght=400
inst "$TMP/karla.ttf"    Karla-Bold         wght=700
inst "$TMP/karla-i.ttf"  Karla-Italic       wght=400
inst "$TMP/karla-i.ttf"  Karla-BoldItalic   wght=700

python3 - "$TMP" "$OUT" <<'PY'
import base64, os, sys
tmp, out = sys.argv[1], sys.argv[2]
names = ["Fraunces-Bold", "Karla-Regular", "Karla-Bold", "Karla-Italic", "Karla-BoldItalic"]
lines = ["/* GENERATED by scripts/build-pdf-fonts.sh — do not edit by hand.",
         "   Fraunces and Karla, SIL Open Font License 1.1, instanced from the",
         "   Google Fonts variable originals and subset to Latin + punctuation.",
         "   pdfmake reads these as its virtual file system when embedding fonts. */",
         "export const VFS = {"]
total = 0
for n in names:
    b = open(os.path.join(tmp, n + ".ttf"), "rb").read()
    total += len(b)
    lines.append('  "%s.ttf": "%s",' % (n, base64.b64encode(b).decode()))
lines.append("};\n")
open(out, "w").write("\n".join(lines))
print("%s — %d fonts, %.0f KB raw, %.0f KB base64" % (out, len(names), total/1024, os.path.getsize(out)/1024))
PY
