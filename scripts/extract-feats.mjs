/* ------------------------------------------------------------------
   Regenerates src/data/feats.js from a local 5etools-src checkout.
   Run from the repo root:  node scripts/extract-feats.mjs

   Sources: PHB, XGE and TCE.  The Handbook's 42 come along with the
   two new books' 30 because a level-4 "feat instead of an ability
   score improvement" choice that offered only Xanathar's and Tasha's
   feats would be a stranger thing than either including or excluding
   feats wholesale.

   Artificer Initiate is dropped: it grants artificer cantrips and
   1st-level spells, and this app has no artificer — the same call the
   Strixhaven spell pull made about artificer class tags.

   Prerequisites are structured, not prose, because the app filters
   rather than validates: a feat you can't take is never rendered.
------------------------------------------------------------------- */
import { readJson, fmtEntries, stripTags, writeFile, q } from "./lib/fivetools.mjs";

const SOURCES = { PHB: "phb", XGE: "xge", TCE: "tce" };
const DROP = new Set(["Artificer Initiate"]);

/* 5etools subrace names -> this app's lineage ids. */
const SUBRACE_ID = { drow: "dark-elf", high: "high-elf", wood: "wood-elf" };

const slug = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

function prereq(f) {
  const out = {};
  const notes = [];
  for (const p of f.prerequisite || []) {
    if (p.ability) {
      out.abilities = p.ability.map((a) => Object.entries(a)[0]).map(([k, v]) => ({ key: k, min: v }));
      notes.push(out.abilities.map((a) => `${a.key.toUpperCase()} ${a.min}`).join(" or "));
    }
    if (p.race) {
      const races = [];
      for (const r of p.race) {
        if (r.name === "small race") { out.small = true; notes.push("a Small race"); continue; }
        races.push({ base: slug(r.name), lineage: r.subrace ? SUBRACE_ID[r.subrace] : null });
        notes.push(r.subrace ? `${r.subrace} ${r.name}` : r.name);
      }
      if (races.length) out.races = races;
    }
    /* `spellcasting` is "can already cast at least one spell";
       `spellcasting2020` is Tasha's looser "has the Spellcasting or
       Pact Magic feature". Both land on the same test here, since this
       app only ever gives a character one class. */
    if (p.spellcasting || p.spellcasting2020) { out.spellcasting = true; notes.push("the ability to cast at least one spell"); }
    for (const pr of p.proficiency || []) {
      if (pr.armor) { out.armor = pr.armor; notes.push(`${pr.armor} armor proficiency`); }
      if (pr.weapon) { out.weapon = pr.weapon; notes.push(`${pr.weapon} weapon proficiency`); }
    }
  }
  return { prereq: Object.keys(out).length ? out : null, prereqText: notes.join(", ") };
}

function abilityBonus(f) {
  const a = (f.ability || [])[0];
  if (!a) return null;
  if (a.choose) return { from: a.choose.from, amount: a.choose.amount || 1 };
  const [key, amount] = Object.entries(a)[0];
  return { fixed: key, amount };
}

const feats = readJson("feats.json").feat
  .filter((f) => SOURCES[f.source] && !DROP.has(f.name))
  .map((f) => {
    const { prereq: pre, prereqText } = prereq(f);
    return {
      id: slug(f.name), name: f.name, src: SOURCES[f.source], page: f.page,
      ability: abilityBonus(f), prereq: pre, prereqText,
      text: fmtEntries(f.entries),
    };
  })
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = feats.map((f) => {
  const bits = [`    id: ${q(f.id)}, name: ${q(f.name)}, src: ${q(f.src)}, page: ${f.page},`];
  if (f.ability) bits.push(`    ability: ${JSON.stringify(f.ability)},`);
  if (f.prereq) bits.push(`    prereq: ${JSON.stringify(f.prereq)},`);
  if (f.prereqText) bits.push(`    prereqText: ${q(f.prereqText)},`);
  bits.push(`    text: ${q(f.text)},`);
  return `  {\n${bits.join("\n")}\n  },`;
}).join("\n");

writeFile("src/data/feats.js", `/* ------------------------------------------------------------------
   GENERATED by scripts/extract-feats.mjs — do not hand-edit.

   ${feats.length} feats: ${feats.filter((f) => f.src === "phb").length} from the Player's Handbook, ${feats.filter((f) => f.src === "xge").length} from
   Xanathar's Guide (all of them racial), ${feats.filter((f) => f.src === "tce").length} from Tasha's Cauldron.
   Artificer Initiate is deliberately absent — no artificer here.

   Fields:
     ability     the half-feat's +1. { fixed: "con", amount: 1 } for a
                 fixed one, { from: [...], amount: 1 } where the feat
                 lets you choose. Absent on a full feat.
     prereq      structured so the picker can filter rather than warn:
                   abilities  [{ key, min }] — ANY one satisfies it
                   races      [{ base, lineage }] — lineage null means
                              any lineage of that base race
                   small      true for "a Small race"
                   spellcasting / armor / weapon
     prereqText  the same thing in the book's words, for display.
------------------------------------------------------------------- */
export const FEATS = [
${lines}
];
`);
console.log(`feats: ${feats.length}`);
